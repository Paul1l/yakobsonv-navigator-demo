// Состав работ, задача формы и кейс подтягиваются из общего контента — один источник правды
export const directions = DIRECTIONS.map((d) => {
  const solution = solutions.items.find((s) => s.id === d.solutionId);
  if (!solution) throw new Error(`directions: нет решения ${d.solutionId}`);
  const relatedCase = d.caseId ? cases.items.find((c) => c.id === d.caseId) ?? null : null;
  return {
    ...d,
    includes: solution.includes.slice(0, 5),
    task: solution.task,
    discuss: solution.cta,
    case: relatedCase,
  };
});
